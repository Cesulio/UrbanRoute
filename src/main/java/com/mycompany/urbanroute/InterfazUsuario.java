    /**
     * Llena dinámicamente el ComboBox de origen y destino con las estaciones del grafo.
     */
    private void cargarEstacionesEnCombos() {
        comboOrigen.removeAllItems();
        comboDestino.removeAllItems();
        
        Lista<String> ids = grafoRed.getIdsEstaciones();
        for (int i = 0; i < ids.getTamano(); i++) {
            String id = ids.obtener(i);
            Estacion est = grafoRed.obtenerEstacion(id);
            if (est != null) {
                // Formato real: "ID - Nombre de la Estación"
                String itemCombo = id + " - " + est.getNombre();
                comboOrigen.addItem(itemCombo);
                comboDestino.addItem(itemCombo);
            }
        }
    }

