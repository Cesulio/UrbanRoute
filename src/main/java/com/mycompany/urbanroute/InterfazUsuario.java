    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {                                          
        // TODO add your handling code here:
        int respuesta = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "¿Desea guardar los datos actuales en memoria antes de cargar un nuevo archivo?",
            "Advertencia de Sobrescritura",
            javax.swing.JOptionPane.YES_NO_CANCEL_OPTION,
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        
        if (respuesta == javax.swing.JOptionPane.CANCEL_OPTION) return;
        if (respuesta == javax.swing.JOptionPane.YES_OPTION) {
            javax.swing.JOptionPane.showMessageDialog(this, "Datos guardados exitosamente.");
        }
        
        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
        int resultado = fileChooser.showOpenDialog(this);
        
        if (resultado == javax.swing.JFileChooser.APPROVE_OPTION) {
            java.io.File archivoSeleccionado = fileChooser.getSelectedFile();
            txtResultados.setText("Archivo seleccionado manualmente:\n" + archivoSeleccionado.getAbsolutePath() + "\n");
        }
    }                                         

    private void btnSubredesActionPerformed(java.awt.event.ActionEvent evt) {                                            
        // TODO add your handling code here:
        Lista<Lista<String>> subredes = AnalizadorRed.detectarSubredes(grafoRed);
    
    txtResultados.setText("=== REPORTE DE SUBREDES (BFS) ===\n\n");
        for (int i = 0; i < subredes.getTamano(); i++) {
            txtResultados.append("Subred aislada #" + (i + 1) + ":\n");
            Lista<String> componente = subredes.obtener(i);
            
            txtResultados.append("  [ ");
            for (int j = 0; j < componente.getTamano(); j++) {
                txtResultados.append(componente.obtener(j) + " ");
            }
            txtResultados.append("]\n\n");
        }
    }                                           

