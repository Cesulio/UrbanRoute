    private void btnRutaActionPerformed(java.awt.event.ActionEvent evt) {                                        
        // TODO add your handling code here:
        if (comboOrigen.getSelectedItem() == null || comboDestino.getSelectedItem() == null) {
            txtResultados.setText("Por favor seleccione una estación de origen y un destino válidas.");
            return;
    }                                       

        String seleccionOrigen = comboOrigen.getSelectedItem().toString();
        String seleccionDestino = comboDestino.getSelectedItem().toString();
        
        String idOrigen = seleccionOrigen.split(" - ")[0].trim();
        String idDestino = seleccionDestino.split(" - ")[0].trim();
        
        // Calculamos la ruta óptima utilizando el algoritmo de Dijkstra en AnalizadorRed
        String resultadoRuta = AnalizadorRed.calcularRutaDijkstra(grafoRed, idOrigen, idDestino);
        
        txtResultados.setText("=== RUTA ÓPTIMA (DIJKSTRA) ===\n\n" + resultadoRuta);
    }                                     

